const slim = new Set(classesFromCss(read('dist/farvist-slim.css')));
const ai = classesFromCss(read('dist/farvist-ai.css'));
const manifest = {
  $comment: 'GENERATED by scripts/gen-agent-files.mjs from the compiled CSS. Used by `npx farvist check`.',
  version: V,
  full,
  notInSlim: full.filter((c) => !slim.has(c)),
  ai,
};
write('dist/farvist.classes.json', JSON.stringify(manifest) + '\n');

