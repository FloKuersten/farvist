const V = ctx.version;
const MAJOR = V.split('.')[0];
const CDN = `https://cdn.jsdelivr.net/npm/farvist@${MAJOR}`;
const size = (file) => { const b = ctx.install.builds.find((x) => x.file === file); return b ? `~${b.gzipKb} KB gzip` : ''; };

